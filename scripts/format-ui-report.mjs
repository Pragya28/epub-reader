#!/usr/bin/env node
// Reads impeccable `detect --json` output from stdin, writes UI_REPORT.md to stdout.
import { readFileSync } from "node:fs";

const raw = readFileSync(0, "utf8").trim();
const findings = raw ? JSON.parse(raw) : [];

const lines = [
  "# UI Report",
  "",
  `Generated by the Impeccable pre-commit hook. ${findings.length} finding(s).`,
  "",
];

if (findings.length === 0) {
  lines.push("No anti-patterns found in staged UI files.");
} else {
  const byFile = new Map();
  for (const f of findings) {
    if (!byFile.has(f.file)) byFile.set(f.file, []);
    byFile.get(f.file).push(f);
  }

  for (const [file, fileFindings] of byFile) {
    lines.push(`## ${file}`, "");
    for (const f of fileFindings) {
      lines.push(`- **[${f.severity}] ${f.name}** (\`${f.antipattern}\`) — line ${f.line}`);
      lines.push(`  ${f.snippet}`);
    }
    lines.push("");
  }
}

process.stdout.write(lines.join("\n") + "\n");
